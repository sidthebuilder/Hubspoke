"""Appendix D: every dated prediction in PREREGISTRATION.md, how it resolved, and a Brier score. Reads the result
files only. Writes report/appendix_predictions.md. Usage: python report/predictions_table.py

The probabilities and wording are copied from PREREGISTRATION.md. Round-1 predictions were made for the main model (Qwen) and are scored on it only;
round-2 predictions are scored on each model that ran the registered test."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
MODELS = [("Qwen2.5-72B", "", ""), ("Llama-3.1-70B", "_llama", "_llama"), ("gpt-oss-120b", "_gptoss", "_gptoss")]

MADE1, MADE2, MADE_HOLD = "24 Oct 19:37 (e3656ec)", "25 Oct 00:06 (d2dbc03)", "24 Oct 21:01 (f3f272e)"  # commit times
ROUND1 = [  # (key prefix in numbers.json, probability, committed)
    ("P1", 0.20, MADE1), ("P2", 0.35, MADE1), ("P3", 0.25, MADE1), ("P4", 0.30, MADE1), ("P5", 0.65, MADE1)]
ROUND2 = [("P6", 0.70), ("P7", 0.75), ("P8", 0.50), ("P9", 0.60)]


def load(p: Path):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def fmt(v):
    if v is None:
        return "n/a"
    if isinstance(v, bool):
        return str(v)
    if isinstance(v, (int, float)):
        return f"{v:+.2f}" if abs(v) < 10 else f"{v:.0f}"
    if isinstance(v, list):
        return ", ".join(fmt(x) for x in v)
    if isinstance(v, dict):
        return "; ".join(f"{k} {fmt(x)}" for k, x in v.items())
    return str(v)


def main():
    rows = []  # (id, made, model, prediction, p, value, outcome)
    n = load(R / "main" / "numbers.json") or {}
    for pid, p, made in ROUND1:
        key = next((k for k in n.get("predictions", {}) if k.startswith(pid + " ")), None)
        if key:
            d = n["predictions"][key]
            val = fmt(d["value"]) if d["holds"] is not None else "premise failed (it needs pooled > isolated, or aged < pooled)"
            rows.append((pid, made, "Qwen2.5-72B", key[len(pid) + 1:], p, val, d["holds"]))
    ex = load(R / "main_llama" / "exploratory.json") or {}
    if "_gap_auroc" in ex:
        a = ex["_gap_auroc"]["auroc"]
        rows.append(("hold-out", MADE_HOLD, "Llama-3.1-70B",
                     "price-gap statistic separates pooled from isolated with AUROC >= 0.75", None,
                     f"{a:.2f} (CI {ex['_gap_auroc']['ci'][0]:.2f} to {ex['_gap_auroc']['ci'][1]:.2f})", a >= 0.75))
    for model, csuf, ssuf in MODELS:
        c2 = load(R / f"canary2{csuf}" / "round2.json")
        if c2:
            for pid, p in ROUND2:
                key = next((k for k in c2.get("predictions", {}) if k.startswith(pid + " ")), None)
                if key:
                    d = c2["predictions"][key]
                    rows.append((pid, MADE2, model, key[len(pid) + 1:], p, fmt(d["value"]), d["holds"]))
        sl = load(R / f"startlow{ssuf}" / "round2.json") if ssuf != "_gptoss" else None
        if sl and "H5 isolated vs solo" in sl:
            h5 = sl["H5 isolated vs solo"]
            rows.append(("start-low", MADE2, model, "inertia: start-low isolated - solo <= 0", 0.65,
                         f"{h5['diff']:+.3f} ({h5['decision']})", h5["diff"] <= 0))
    scored = [(p, o) for *_, p, _, o in rows if p is not None and o is not None]
    brier = sum((p - (1.0 if o else 0.0)) ** 2 for p, o in scored) / len(scored) if scored else None
    L = ["# Appendix D: dated predictions and how they resolved", "",
         "Generated by report/predictions_table.py from the result files. Every prediction was written into "
         "PREREGISTRATION.md before the data it predicts existed, and checked by the author.", "",
         "| id | committed (IST, commit) | model | prediction | p | observed | held |", "|---|---|---|---|---|---|---|"]
    for pid, made, model, text, p, val, o in rows:
        L.append(f"| {pid} | {made} | {model} | {text} | {'' if p is None else f'{p:.2f}'} | {val} | "
                 f"{'not scored' if o is None else ('yes' if o else 'no')} |")
    if brier is not None:
        held = sum(1 for _, o in scored if o)
        L += ["", f"{held} of {len(scored)} scored predictions held. Brier score {brier:.3f} over the {len(scored)} "
              f"scored predictions with a probability (0 = perfect; always saying 0.5 scores 0.250)."]
    weak = []
    for model, csuf, _ in MODELS:
        c2 = load(R / f"canary2{csuf}" / "round2.json")
        t = (c2 or {}).get("tests (registered, judged disclosure of price plans)", {}).get("shared vs private")
        if t and t["p"] >= 0.05:
            weak.append(f"{model} (shared vs private, Fisher p = {t['p']:.2f})")
    if weak:
        L += ["", "P8 and P9 were registered without a premise. Where judged disclosure with a shared notebook was not "
              "clearly above the private-notebook level, they hold without a leak to cut: " + "; ".join(weak) + "."]
    jv = load(R / "judge_validation.json") or {}
    k = (jv.get("judge vs human") or {}).get("kappa")
    L += ["", "P7-P9 use the judged disclosure measure. " + (
        f"Its agreement with the blind human rater: kappa {k:.2f} "
        f"({'primary measure' if k >= 0.6 else 'below 0.6, so judged disclosure is secondary (registered rule)'})."
        if k is not None else "The judge has not yet been checked against the blind human rater (R2.2).")]
    (ROOT / "report" / "appendix_predictions.md").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
