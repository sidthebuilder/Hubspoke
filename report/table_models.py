"""The report's main tables, side by side for every model that ran: price index by condition, the registered tests,
the start-low test, and the canary v2 price-plan results. Reads result files only; writes report/table_models.md.
Usage: python report/table_models.py"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from hubspoke import stats  # noqa: E402

R = ROOT / "results"
MODELS = [("Qwen2.5-72B", "main", "startlow", "canary2"), ("Llama-3.1-70B", "main_llama", "startlow_llama", "canary2_llama"),
          ("gpt-oss-120b", "main_gptoss", None, "canary2_gptoss")]
CONDS = ["solo", "chat", "isolated", "pooled", "aged", "aged_sharedmem", "portfolio"]
LABEL = {"solo": "solo (no advisor)", "chat": "chat (+ control)", "isolated": "isolated", "pooled": "pooled",
         "aged": "aged", "aged_sharedmem": "aged + shared notebook", "portfolio": "portfolio (+ control)",
         "separate": "separate (exploratory)"}


def load(p: Path):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def cell(m, lo, hi):
    return f"{m:+.2f} ({lo:+.2f} to {hi:+.2f})"


def main():
    have = [(name, load(R / f / "numbers.json"), load(R / f / "exploratory.json"), sl, c2)
            for name, f, sl, c2 in MODELS if (R / f / "numbers.json").exists()]
    L = ["# Main tables, every model (generated by report/table_models.py)", "",
         "## Price index, periods 26-40 (0 = Nash, 1 = joint profit); mean over 12 runs (95% bootstrap CI)", "",
         "| condition | " + " | ".join(n for n, *_ in have) + " |", "|---|" + "---|" * len(have)]
    for c in CONDS + ["separate"]:
        row = []
        for _, n, ex, *_ in have:
            v = n["summary"]["conditions"].get(c)
            if v:
                row.append(cell(v["index_mean"], *v["index_ci"]))
            elif c == "separate" and ex and "separate" in ex:
                xs = [r["p26_40"] for r in ex["separate"]["runs"]]
                row.append(cell(stats.mean(xs), *stats.bootstrap_mean_ci(xs, seed=1)))
            else:
                row.append("")
        if any(row):
            L.append(f"| {LABEL[c]} | " + " | ".join(row) + " |")
    L += ["", "## Registered tests (exact permutation tests on run means, 12 vs 12; Holm over H1-H4 within a model)", "",
          "| test | " + " | ".join(n for n, *_ in have) + " |", "|---|" + "---|" * len(have)]
    for t in ("H1 pooled > isolated", "H2 aged < pooled", "H3 aged_sharedmem > aged", "H4 isolated vs solo"):
        row = []
        for _, n, *_ in have:
            x = n["tests"].get(t)
            row.append("" if not x else f"{x['diff']:+.2f} ({x['ci'][0]:+.2f} to {x['ci'][1]:+.2f}); p {x['p']:.3f}, "
                                        f"Holm {x['p_holm']:.3f}")
        L.append(f"| {t} | " + " | ".join(row) + " |")
    row = []
    for name, n, *_ in have:
        cs = n["summary"]["conditions"]
        d = cs["portfolio"]["index_mean"] - cs["isolated"]["index_mean"] if "portfolio" in cs and "isolated" in cs else None
        row.append("" if d is None else f"{d:+.2f} ({'capable hub' if d >= 0.15 else 'not capable'})")
    L.append("| hub check: portfolio - isolated >= 0.15 (registered for gpt-oss in R2.4; shown for every model) | "
             + " | ".join(row) + " |")

    sl_models = [(name, load(R / sl / "round2.json")) for name, _, _, sl, _ in have if sl and (R / sl / "round2.json").exists()]
    if sl_models:
        L += ["", "## Start-low test (R2.3): pre-periods below the Nash price; index, periods 26-40", "",
              "| condition | " + " | ".join(n for n, _ in sl_models) + " |", "|---|" + "---|" * len(sl_models)]
        conds = [c for c in ("solo", "isolated", "pooled", "portfolio", "separate") if c in sl_models[0][1]["conditions"]]
        for c in conds:
            L.append(f"| {LABEL[c]} | " + " | ".join(cell(o["conditions"][c]["index"]["mean"], *o["conditions"][c]["index"]["ci"])
                                                       for _, o in sl_models) + " |")
        L.append("| pre-periods (start) | " + " | ".join(f"{o['conditions']['solo']['start']['mean']:+.2f}" for _, o in sl_models) + " |")
        L.append("| H5 isolated - solo (exact p, two-sided) | " + " | ".join(
            f"{o['H5 isolated vs solo']['diff']:+.3f} (p {o['H5 isolated vs solo']['p_two_sided']:.3f}): "
            f"{o['H5 isolated vs solo']['decision']}" for _, o in sl_models) + " |")
        L.append("| H6 isolated change from its start (sign-flip p) | " + " | ".join(
            f"{o['H6 isolated change from its pre-periods']['mean']:+.3f} (p {o['H6 isolated change from its pre-periods']['p_two_sided']:.3f})"
            for _, o in sl_models) + " |")

    c2_models = [(name, load(R / c2 / "round2.json")) for name, *_, c2 in have if (R / c2 / "round2.json").exists()]
    if c2_models:
        L += ["", "## Canary v2 (R2.1), planted price plans: 24 trials per cell", "",
              "| model | notebook | written | reaches B's session | exact number in B's advice | judged reveal | judge on control | B's price shift (95% CI) |",
              "|---|---|---|---|---|---|---|---|"]
        for name, o in c2_models:
            for arm in ("private", "shared", "shared_rule", "shared_tags"):
                c = o["cells"].get(f"price|{arm}")
                if not c:
                    continue
                f = lambda r: f"{r['k']}/{r['n']}" if r and r["n"] else "n/a"  # noqa: E731
                sh = c["shift"]
                L.append(f"| {name} | {arm} | {f(c['written'])} | {f(c['exposed'])} | {f(c['disclosed_exact'])} | "
                         f"{f(c['disclosed_judged'])} | {f(c['control_judged (exploratory false-positive baseline)'])} | "
                         f"{sh['mean']:+.3f} ({sh['ci'][0]:+.3f} to {sh['ci'][1]:+.3f}) |")
        L += ["", "Other planted facts (all four notebooks pooled, 96 trials per fact): written / exact number in B's advice", ""]
        for name, o in c2_models:
            parts = []
            for kind in ("code", "town", "cost", "price"):
                cs = [o["cells"][f"{kind}|{a}"] for a in ("private", "shared", "shared_rule", "shared_tags") if f"{kind}|{a}" in o["cells"]]
                w = sum(c["written"]["k"] for c in cs)
                e = sum(c["disclosed_exact"]["k"] for c in cs)
                n = sum(c["written"]["n"] for c in cs)
                parts.append(f"{kind} {w}/{n} written, {e}/{n} exact")
            L.append(f"- {name}: " + "; ".join(parts))
    (ROOT / "report" / "table_models.md").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
